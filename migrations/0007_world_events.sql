CREATE TABLE IF NOT EXISTS world_event_progress (
 userId TEXT NOT NULL REFERENCES user(id) ON DELETE CASCADE,eventId TEXT NOT NULL,
 foundAt INTEGER NOT NULL,inspectedAt INTEGER,transcript TEXT NOT NULL DEFAULT '[]',turns INTEGER NOT NULL DEFAULT 0,
 updatedAt INTEGER NOT NULL,lastAIAt INTEGER NOT NULL DEFAULT 0,leaseToken TEXT,leaseUntil INTEGER NOT NULL DEFAULT 0,lastRequestId TEXT,
 PRIMARY KEY(userId,eventId)
);
